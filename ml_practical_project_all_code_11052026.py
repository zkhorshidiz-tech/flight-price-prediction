# Purpose: Test whether ticket prices differ by airline

# =========================================================



def eta_squared_anova(data, group_col, target_col):

    grand_mean = data[target_col].mean()

    ss_between = sum(

        len(group) * (group[target_col].mean() - grand_mean) ** 2

        for _, group in data.groupby(group_col)

    )

    ss_total = ((data[target_col] - grand_mean) ** 2).sum()

    return ss_between / ss_total



airline_groups = [group["price"].values for _, group in df_clean.groupby("airline")]



f_stat, p_value = f_oneway(*airline_groups)

eta_airline = eta_squared_anova(df_clean, "airline", "price")



print("ANOVA for Airline")

print("F-statistic:", f_stat)

print("p-value:", p_value)

print("Eta squared:", eta_airline)



# =========================================================

# Purpose: Test whether ticket prices differ between Business and Economy

# =========================================================



business_price = df_clean[df_clean["class"] == "Business"]["price"]

economy_price = df_clean[df_clean["class"] == "Economy"]["price"]



t_stat, p_value = ttest_ind(business_price, economy_price, equal_var=False)



def cohens_d(x, y):

    nx, ny = len(x), len(y)

    pooled_std = np.sqrt(

        ((nx - 1) * x.var(ddof=1) + (ny - 1) * y.var(ddof=1)) / (nx + ny - 2)

    )

    return (x.mean() - y.mean()) / pooled_std





class_cohens_d = cohens_d(business_price, economy_price)



print("Welch T-test for Class")

print("T-statistic:", t_stat)

print("p-value:", p_value)

print("Cohen's d:", class_cohens_d)



